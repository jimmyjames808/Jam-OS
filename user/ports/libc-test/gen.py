#!/usr/bin/env python3
"""The test table of the libc-test port (user/ports/libc-test/).

    gen.py tests <libc-test dir> <expected-failures.txt>
        the tests to build, one "set/name" a line
    gen.py table <libc-test dir> <expected-failures.txt>
        the C file with the table of those tests and the expected list

A test is a .c file of src/functional or src/regression, except a *_dso.c
(a helper the dynamic tests load). The expected-failures file has a line a
test, `set/name  kind: reason`, with the kinds enosys (by design), limit
(a known Jam OS limit), bug (a bug of ours, to fix), pending (waits for
another track) and skip (the test is not built: dynamic linking). Every
name must be a test of the tree, and every `skip` one is left out."""
import os
import sys

SETS = ("functional", "regression")
KINDS = ("enosys", "limit", "bug", "pending", "skip")


def die(msg):
    sys.exit("libc-test gen: " + msg)


def all_tests(root):
    found = []
    for s in SETS:
        for f in sorted(os.listdir(os.path.join(root, "src", s))):
            if f.endswith(".c") and not f.endswith("_dso.c"):
                found.append(s + "/" + f[:-2])
    return found


def read_expected(path, tests):
    expected = {}
    for n, line in enumerate(open(path), 1):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        name, _, why = line.partition(" ")
        why = why.strip()
        kind, _, rest = why.partition(":")
        if name not in tests:
            die("%s:%d: %s is not a test" % (path, n, name))
        if name in expected:
            die("%s:%d: %s twice" % (path, n, name))
        if kind not in KINDS or not rest.strip():
            die("%s:%d: want 'kind: reason' with kind one of %s" % (path, n, ", ".join(KINDS)))
        expected[name] = why
    return expected


def c_string(text):
    return text.replace("\\", "\\\\").replace('"', '\\"')


def symbol(name):
    return "lct_" + name.replace("/", "_").replace("-", "_")


def main():
    if len(sys.argv) != 4 or sys.argv[1] not in ("tests", "table"):
        sys.exit(__doc__)
    root, tests = sys.argv[2], all_tests(sys.argv[2])
    expected = read_expected(sys.argv[3], tests)
    built = [t for t in tests if not expected.get(t, "").startswith("skip:")]
    if sys.argv[1] == "tests":
        print("\n".join(built))
        return
    out = ["/* Generated by user/ports/libc-test/gen.py: do not edit. */",
           '#include "lct.h"', ""]
    out += ["int %s(int, char **);" % symbol(t) for t in built]
    out += ["", "const struct lct_test lct_tests[] = {"]
    out += ['    { "%s", %s },' % (t, symbol(t)) for t in built]
    out += ["};", "const unsigned lct_ntests = %d;" % len(built), "",
            "const struct lct_expect lct_expected[] = {"]
    out += ['    { "%s", "%s" },' % (t, c_string(expected[t])) for t in tests if t in expected]
    out += ["};", "const unsigned lct_nexpected = %d;" % len(expected)]
    print("\n".join(out))


main()
