#!/bin/sh
# mkbox.sh <box name> root|plain <command>...: the C source of a box, a multi-call
# program of Jam OS's own commands (the same idea as user/ports/sbase/mkbox.sh).
# A command is a shell command's name (user/services/shell/cmd/<name>.c,
# SH_CMD(<name>)), or <alias>=<name> for another name of one (hd=hexdump).
# The main picks the command by the basename of argv[0], the name the
# program was started as (the shell starts a program by its bootfs name,
# bin/dmesg). Started as the box's own name, it takes the command from the
# first argument: `sys-info free`; with none, it lists its commands.
# root: the commands use the root resource (the box's list has a `right`):
# without it (started by a POSIX parent, which doesn't pass it on) the
# command says so and ends with status 126 instead of failing in a call.
set -eu
box=$1
needs_root=$2
shift 2
case $needs_root in
root) needs_root=1 ;;
plain) needs_root=0 ;;
*) echo "mkbox.sh: root or plain, not $needs_root" >&2; exit 2 ;;
esac
cat <<EOT
/* Generated by user/sysbox/mkbox.sh: the multi-call program $box. */
#include <libgen.h>
#include <stdio.h>
#include <string.h>

#include "box.h"

EOT
for c in "$@"; do
    printf 'int shc_%s(int, char **);\n' "${c#*=}"
done
cat <<EOT

static const struct { const char *name; int (*fn)(int, char **); } cmds[] = {
EOT
for c in "$@"; do
    case $c in
    *=*) printf '\t{ "%s", shc_%s },\n' "${c%%=*}" "${c#*=}" ;;
    *) printf '\t{ "%s", shc_%s },\n' "$c" "$c" ;;
    esac
done
cat <<EOT
	{ NULL, NULL },
};

int
main(int argc, char *argv[])
{
	char copy[256];
	const char *s;
	int i;

	strncpy(copy, argv[0], sizeof(copy) - 1);
	copy[sizeof(copy) - 1] = '\0';
	s = basename(copy);
	if (!strcmp(s, "$box") && argc > 1) {
		argc--;
		argv++;
		strncpy(copy, argv[0], sizeof(copy) - 1);
		s = basename(copy);
	}
	for (i = 0; cmds[i].name; i++) {
		if (!strcmp(cmds[i].name, s))
			return box_init(s, $needs_root) ? 126 : cmds[i].fn(argc, argv);
	}
	for (i = 0; cmds[i].name; i++)
		printf("%s ", cmds[i].name);
	putchar('\n');
	return !strcmp(s, "$box") ? 0 : 127;
}
EOT
