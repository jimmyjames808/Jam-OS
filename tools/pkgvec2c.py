#!/usr/bin/env python3
"""The ports formats' test vectors as a C file (the Makefile runs it):

    pkgvec2c.py <vectors dir> <out.c>

Every file of ports/vectors/ (PO3's packages, indexes, VULNS, CASES and
test.pub, which `tools/ports.py vectors` makes and checks) becomes a byte
array in the table pkgv_files (user/tests/utest/pkgcases.h), so utest on
Jam OS reads the very bytes `make check` reads on the Mac. Files are in
name order; the output is a function of the directory alone."""
import os
import sys


def main(argv):
    if len(argv) != 3:
        print(__doc__)
        return 2
    src, out = argv[1], argv[2]
    names = sorted(n for n in os.listdir(src) if not n.startswith("."))
    lines = ["/* Generated by tools/pkgvec2c.py from ports/vectors: do not edit. */",
             '#include "pkgcases.h"', ""]
    for i, n in enumerate(names):
        with open(os.path.join(src, n), "rb") as f:
            data = f.read()
        lines.append("static const uint8_t v%d[%d] = {" % (i, max(len(data), 1)))
        for at in range(0, len(data), 16):
            lines.append("    " + ", ".join("0x%02x" % b for b in data[at:at + 16]) + ",")
        if not data:
            lines.append("    0,")
        lines.append("};")
    lines += ["", "static const struct pkgv_file files[] = {"]
    lines += ['    { "%s", v%d, %d },' % (n, i, os.path.getsize(os.path.join(src, n)))
              for i, n in enumerate(names)]
    lines += ["};", "", "const struct pkgv_file *pkgv_files = files;",
              "unsigned pkgv_nfiles = %d;" % len(names), ""]
    tmp = out + ".tmp"
    with open(tmp, "w") as f:
        f.write("\n".join(lines))
    os.replace(tmp, out)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
