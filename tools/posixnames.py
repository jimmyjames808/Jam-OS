#!/usr/bin/env python3
"""The POSIX layer's global names, made the implementation's own.

The call layer (user/posix/sys/, user/posix/crt/) goes into libc.a beside
musl, so its global names (fd_get, path_get, poll_run, lx_read, ...) would
be in every program's name space: a port that defines one fails to link,
or has the layer call its function. user/posix/posix.mk renames them in
libc.a's copies of the layer's objects with `objcopy --redefine-syms`, to
`__jl_<name>`: names beginning with two underscores are reserved to the
implementation, so no conforming program defines one. This script makes
the list from the objects themselves, so nothing is maintained by hand:

    posixnames.py <nm> <map out> <header out> <object>...

Every global symbol an object defines is renamed but those already
reserved (`__*`: the entry points musl's overrides call, __jam_*) and the
public extensions a program calls (`jamos_*`, <jamos/*.h>). The header
gives the same renames as #defines, for the one test that reaches into the
layer (posixtest's fileskid.c, through fd.h). Both files are written only
when their contents change, so a build that changes no name redoes no
renaming."""
import subprocess
import sys

PREFIX = '__jl_'


def kept(name):
    return name.startswith('__') or name.startswith('jamos_')


def defined_globals(nm, objs):
    out = subprocess.run([nm, '-g', '--defined-only', '-P'] + objs, capture_output=True,
                         text=True, check=True).stdout
    names = set()
    for line in out.splitlines():
        parts = line.split()
        if len(parts) >= 2 and not parts[0].endswith(':') and parts[1] not in 'Uw':
            names.add(parts[0])
    return sorted(n for n in names if not kept(n))


def write_if_changed(path, text):
    try:
        with open(path) as f:
            if f.read() == text:
                return
    except OSError:
        pass
    with open(path, 'w') as f:
        f.write(text)


def main():
    if len(sys.argv) < 5:
        sys.exit(__doc__)
    nm, map_out, h_out, objs = sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4:]
    names = defined_globals(nm, objs)
    write_if_changed(map_out, ''.join(f'{n} {PREFIX}{n}\n' for n in names))
    write_if_changed(h_out, '/* Generated by tools/posixnames.py: the layer\'s renamed names. */\n'
                     '#pragma once\n' + ''.join(f'#define {n} {PREFIX}{n}\n' for n in names))
    print(f'posixnames: {len(names)} names of the layer renamed {PREFIX}*')


if __name__ == '__main__':
    main()
