#!/usr/bin/env python3
"""Generate the system call glue from abi/syscalls.def (format described
at the top of that file).

    gensyscalls.py gen     write the generated files
    gensyscalls.py check   exit 1 (and name them) if any is missing or stale

Outputs, all committed so they can be read and grepped like any source:
    kernel/include/jam/syscall_nums.h  SYS_<name> numbers (shared with user code)
    kernel/include/jam/syscall_impl.h  sysc_<name> prototypes for the kernel
    kernel/abi/syscall_table.c         syscall_dispatch and the table
    user/lib/syscalls.S                jam_<name> wrappers
    user/include/jam_syscalls.h        jam_<name> prototypes

There are no default implementations: the kernel must define every
sysc_<name> in the .def, or it doesn't link.

Run from the repository root (the Makefile does)."""
import os
import re
import sys

DEF = "abi/syscalls.def"
ABI_H = "kernel/include/jam/abi.h"
MAX_ARGS = 6
REGS = ["rdi", "rsi", "rdx", "r10", "r8", "r9"]
SCALARS = {"handle_t", "rights_t", "signals_t", "uint32_t", "int32_t", "uint64_t", "int64_t"}
RETURNS = {"status": "status_t", "i64": "int64_t", "noreturn": "_Noreturn void"}
BANNER = "Generated by tools/gensyscalls.py from abi/syscalls.def. Do not edit:\n" \
         " * change the .def and run `make syscalls`."
IDENT = re.compile(r"[A-Za-z_][A-Za-z0-9_]*$")


class Arg:
    def __init__(self, ctype, name):
        self.ctype, self.name = ctype, name
        self.pointer = "*" in ctype

    def kernel_decl(self):
        return f"uint64_t {self.name}" if self.pointer else f"{self.ctype} {self.name}"

    def user_decl(self):
        sep = "" if self.ctype.endswith("*") else " "
        return f"{self.ctype}{sep}{self.name}"


class Call:
    def __init__(self, nr, name, ret, args, struct):
        self.nr, self.name, self.ret, self.args, self.struct = nr, name, ret, args, struct


def fail(lineno, msg):
    sys.exit(f"{DEF}:{lineno}: {msg}")


def parse_arg(lineno, text):
    tokens = text.replace("*", " * ").split()
    if len(tokens) < 2 or not IDENT.match(tokens[-1]):
        fail(lineno, f"bad argument '{text.strip()}' (want '<type> <name>')")
    name = tokens[-1]
    ctype = " ".join(tokens[:-1]).replace("* *", "**")
    if "*" not in ctype and ctype not in SCALARS:
        fail(lineno, f"argument '{name}': type '{ctype}' is not one of {sorted(SCALARS)} "
                     "or a pointer")
    return Arg(ctype, name)


def parse():
    abi = open(ABI_H).read()
    calls, nrs, names = [], set(), set()
    for lineno, line in enumerate(open(DEF), 1):
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        parts = line.split(None, 3)
        if len(parts) < 4:
            fail(lineno, "want '<nr> <name> <return> <arguments>'")
        nr_s, name, ret, rest = parts
        if not nr_s.isdigit() or int(nr_s) == 0 or int(nr_s) > 1023:
            fail(lineno, f"bad number '{nr_s}' (1..1023)")
        nr = int(nr_s)
        if not IDENT.match(name):
            fail(lineno, f"bad name '{name}'")
        if ret not in RETURNS:
            fail(lineno, f"bad return kind '{ret}' (want {', '.join(RETURNS)})")
        if nr in nrs:
            fail(lineno, f"number {nr} used twice")
        if name in names:
            fail(lineno, f"name {name} used twice")
        nrs.add(nr)
        names.add(name)
        args, struct = [], None
        rest = rest.strip()
        if rest.startswith("@"):
            struct = rest[1:]
            if not IDENT.match(struct):
                fail(lineno, f"bad struct name '{struct}'")
            if not re.search(r"\bstruct\s+" + struct + r"\s*\{", abi):
                fail(lineno, f"struct {struct} is not defined in {ABI_H}")
        elif rest != "void":
            args = [parse_arg(lineno, a) for a in rest.split(",")]
            if len(args) > MAX_ARGS:
                fail(lineno, f"{len(args)} arguments: at most {MAX_ARGS} fit in registers; "
                             "use an @struct")
            if len({a.name for a in args}) != len(args):
                fail(lineno, "two arguments with the same name")
        calls.append(Call(nr, name, ret, args, struct))
    if not calls:
        sys.exit(f"{DEF}: no system calls")
    return sorted(calls, key=lambda c: c.nr)


def kernel_params(c):
    if c.struct:
        return f"const struct {c.struct} *args"
    return ", ".join(a.kernel_decl() for a in c.args) or "void"


def user_params(c):
    if c.struct:
        return f"const struct {c.struct} *args"
    return ", ".join(a.user_decl() for a in c.args) or "void"


def gen_nums(calls):
    out = [f"/* {BANNER} */", "#pragma once", ""]
    for c in calls:
        out.append(f"#define SYS_{c.name:<20} {c.nr}")
    out += ["", "/* One past the highest number: the size of the dispatch table. */",
            f"#define SYSCALL_COUNT {calls[-1].nr + 1}", ""]
    return "\n".join(out)


def gen_impl(calls):
    out = [f"/* {BANNER}",
           " *",
           " * The kernel side of every system call. Pointer arguments are user",
           " * addresses (uint64_t): touch them only with copy_from_user/copy_to_user.",
           " * @struct calls get a kernel copy of their argument struct. The result",
           " * goes to user rax. */",
           "#pragma once", "", "#include <stdint.h>", "#include <jam/abi.h>", ""]
    for c in calls:
        out.append(f"int64_t sysc_{c.name}({kernel_params(c)});")
    out.append("")
    return "\n".join(out)


def gen_table(calls):
    out = [f"/* {BANNER}",
           " *",
           " * syscall_dispatch: bounds-check the number, then call sysc_<name> with",
           " * the register arguments cast to their declared types. */",
           "#include <jam/status.h>", "#include <jam/syscall.h>",
           "#include <jam/syscall_impl.h>", "#include <jam/syscall_nums.h>",
           "#include <jam/usercopy.h>", "",
           "typedef int64_t (*syscall_fn)(const struct syscall_frame *f);", ""]
    for c in calls:
        out.append(f"static int64_t call_{c.name}(const struct syscall_frame *f)")
        out.append("{")
        if c.struct:
            out.append(f"    struct {c.struct} a;")
            out.append("    if (copy_from_user(&a, f->args[0], sizeof(a)) != OK)")
            out.append("        return ERR_INVALID_ARGS;")
            out.append(f"    return sysc_{c.name}(&a);")
        else:
            if not c.args:
                out.append("    (void)f;")
            vals = [f"f->args[{i}]" if a.pointer or a.ctype == "uint64_t" else f"({a.ctype})f->args[{i}]"
                    for i, a in enumerate(c.args)]
            out.append(f"    return sysc_{c.name}({', '.join(vals)});")
        out.append("}")
        out.append("")
    out.append("static const syscall_fn syscall_table[SYSCALL_COUNT] = {")
    for c in calls:
        out.append(f"    [SYS_{c.name}] = call_{c.name},")
    out += ["};", "",
            "/* i if i < n, else 0, computed without a branch the CPU could",
            " * speculate past (a mispredicted bounds check must not index the table",
            " * with a user-chosen number). */",
            "static inline uint64_t index_nospec(uint64_t i, uint64_t n)",
            "{",
            "    uint64_t mask;",
            "    __asm__(\"cmp %2, %1; sbb %0, %0\" : \"=r\"(mask) : \"r\"(i), \"r\"(n) : \"cc\");",
            "    return i & mask;",
            "}", "",
            "int64_t syscall_dispatch(struct syscall_frame *f)",
            "{",
            "    uint64_t nr = f->nr;",
            "    if (nr >= SYSCALL_COUNT)",
            "        return ERR_NOT_SUPPORTED;",
            "    syscall_fn fn = syscall_table[index_nospec(nr, SYSCALL_COUNT)];",
            "    if (!fn)",
            "        return ERR_NOT_SUPPORTED;",
            "    return fn(f);",
            "}", ""]
    return "\n".join(out)


def gen_wrappers(calls):
    out = [f"/* {BANNER}",
           " *",
           " * One wrapper per system call: the C arguments are already in rdi rsi",
           " * rdx rcx r8 r9; `syscall` needs the fourth in r10 (it overwrites rcx). */",
           "#include <jam/syscall_nums.h>", "", "    .text"]
    for c in calls:
        out += ["",
                f"    .globl jam_{c.name}",
                f"    .type jam_{c.name}, @function",
                f"jam_{c.name}:"]
        if len(c.args) >= 4:
            out.append("    mov %rcx, %r10")
        out.append(f"    mov ${'SYS_' + c.name}, %eax")
        out.append("    syscall")
        out.append("    ud2" if c.ret == "noreturn" else "    ret")
        out.append(f"    .size jam_{c.name}, . - jam_{c.name}")
    out += ["", '    .section .note.GNU-stack, "", @progbits', ""]
    return "\n".join(out)


def gen_user_header(calls):
    out = [f"/* {BANNER}",
           " *",
           " * System call wrappers (user/lib/syscalls.S). Negative results are",
           " * ERR_* codes from <jam/status.h>. */",
           "#pragma once", "", "#include <stdint.h>", "#include <jam/abi.h>",
           "#include <jam/status.h>", "#include <jam/syscall_nums.h>", ""]
    for c in calls:
        out.append(f"{RETURNS[c.ret]} jam_{c.name}({user_params(c)});")
    out.append("")
    return "\n".join(out)


OUTPUTS = {
    "kernel/include/jam/syscall_nums.h": gen_nums,
    "kernel/include/jam/syscall_impl.h": gen_impl,
    "kernel/abi/syscall_table.c": gen_table,
    "user/lib/syscalls.S": gen_wrappers,
    "user/include/jam_syscalls.h": gen_user_header,
}

# Files this script used to write. The build compiles every kernel/**/*.c,
# so a stale copy (a merge bringing one back) would quietly supply weak
# ERR_NOT_SUPPORTED system calls again: `check` fails on it, `gen` deletes it.
OBSOLETE = ["kernel/abi/syscall_weak.c"]


def main():
    if len(sys.argv) != 2 or sys.argv[1] not in ("gen", "check"):
        sys.exit(__doc__)
    calls = parse()
    stale = []
    for path, fn in OUTPUTS.items():
        text = fn(calls)
        try:
            old = open(path).read()
        except FileNotFoundError:
            old = None
        if old == text:
            continue
        if sys.argv[1] == "gen":
            open(path, "w").write(text)
            print(f"gensyscalls: wrote {path}")
        else:
            stale.append(path)
    for path in OBSOLETE:
        if not os.path.exists(path):
            continue
        if sys.argv[1] == "gen":
            os.remove(path)
            print(f"gensyscalls: deleted {path} (no longer generated)")
        else:
            stale.append(path)
    if stale:
        sys.exit("gensyscalls: generated files are stale or edited by hand "
                 f"({', '.join(stale)}):\nrun `make syscalls` and commit the result")


if __name__ == "__main__":
    main()
