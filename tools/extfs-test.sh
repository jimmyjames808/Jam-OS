#!/bin/sh
# extfs on a Jam OS NVMe drive, with Linux's e2fsprogs as the judge
# (docs/M13.6-PLAN.md, U9). Each case is a shard of its own: give each its
# own output directory to run them side by side. Every case boots a drive
# that is made on the host (tools/mkgpt.py's jamos layout: the ESP, and a
# data partition that is an ext volume Linux's mke2fs made: as tools/nvme-
# test.sh's jam case and tools/pager-test.sh's jam case make one), which
# Jam OS mounts at /jam. These need e2fsprogs and mtools: the test PC's WSL.
#
#     tools/extfs-test.sh <outdir> <case>
#
# Cases:
#   storm  `storm` copies a file of random bytes within /jam (64 MiB) while
#          extfs-jam is killed 0, 1, 10 and 100 times a second: every copy
#          MATCHes (both files hashed again from the disk) and extfs
#          carries on each time, never starting fresh. The volume is clean
#          for e2fsck -fn afterwards.
#
# Into <outdir>: the shell script's log (<case>.log), the host's judges'
# outputs (*.fsck, *.out). Exit 0 when the case passed.
# QEMU_SMP and QEMU_MEM pass through; QEMU_TIMEOUT too.
set -eu
out=${1:?usage: tools/extfs-test.sh <outdir> <case>}
c=${2:?usage: tools/extfs-test.sh <outdir> <case>}
export PATH=/usr/sbin:/sbin:$PATH LC_ALL=C
mkdir -p "$out"
ok=1
name=extfs-$c

count() { grep -acE -- "$1" "$2" || true; }
# want <how many times exactly> <text (a regex)> <log>
want() {
    n=$(count "$2" "$3")
    [ "$n" -eq "$1" ] || { echo "$name: \"$2\" $n times in $(basename "$3"), wanted $1"; ok=0; }
}
never() {   # never <text> <log>
    n=$(count "$1" "$2")
    [ "$n" -eq 0 ] || { echo "$name: \"$1\" $n times in $(basename "$2")"; ok=0; }
}

# The tools the cases need, or say what is missing.
ext_tools() {
    for t in mke2fs debugfs e2fsck mcopy mformat sha256sum; do
        command -v $t > /dev/null 2>&1 && continue
        echo "$name: no $t here (needs e2fsprogs and mtools: the test PC's WSL has them)"
        exit 2
    done
}

# ---- the drive -------------------------------------------------------------------------

# seeded <file> <MiB> <seed>: that many MiB of the same bytes every time.
seeded() {
    python3 -c "import random, sys; sys.stdout.buffer.write(random.Random($3).randbytes($2 << 20))" > "$1"
}

# make_volume <file> <MiB> <tree> [<mke2fs's features>]: an ext volume in
# <file> of that many MiB holding the tree's files, every file owned by
# Jam OS's one user (tools/ext-stick.sh: Jam OS's feature set by default).
make_volume() {
    truncate -s "$2M" "$1"
    tools/ext-stick.sh --volume "$1" "$3" jamdata > "$out/$name-ext.out" 2>&1 ||
        { echo "$name: the ext volume couldn't be made (see $out/$name-ext.out)"; exit 1; }
}

# make_drive <drive> <volume>: <drive> is a 1 GiB Jam OS NVMe drive (the
# ESP a FAT volume, the data partition at 513 MiB holding <volume>).
make_drive() {
    esp="$1.esp"
    truncate -s 128M "$esp"
    mformat -i "$esp" -T $((128 * 2048)) -F -v JAMOS-ESP :: || { echo "$name: mformat"; exit 1; }
    python3 tools/mkgpt.py "$1" --layout jamos --size 1G --fill "1=$esp" --fill "2=$2" > /dev/null
    rm -f "$esp"
}

# clean <drive> <bytes> <what>: the ext volume in the data partition (its
# first <bytes>, copied out) is what e2fsck -fn calls clean.
clean() {
    vol="$out/$name-check.img"
    dd if="$1" of="$vol" bs=1M iflag=skip_bytes,count_bytes skip=$((513 << 20)) count="$2" status=none
    if ! e2fsck -fn "$vol" > "$out/$name-$3.fsck" 2>&1; then
        echo "$name: e2fsck doesn't call the volume clean $3 (see $out/$name-$3.fsck)"
        ok=0
    fi
    rm -f "$vol"
}

# ---- one boot ---------------------------------------------------------------------------

# boot <script> <drive>: the shell script typed into a boot with the drive
# as its NVMe drive; its log (up to the `reboot -f` at the end) into $run.
boot() {
    if ! QEMU_TIMEOUT=${QEMU_TIMEOUT:-600} QEMU_INPUT="$1" QEMU_NVME="$2" \
         tools/qemu-test.sh "$out" "$name" shell > "$out/$name.out" 2>&1; then
        echo "$name: the shell script FAILED (see $out/$name.log)"
        grep "serial-feed: .*no '" "$out/$name.out" || true
        ok=0
    fi
    run="$out/$name.run.log"
    sed '/jam[^>]*>.* reboot -f/q' "$out/$name.log" > "$run"
    want 1 "init: /jam mounted" "$run"
}

# ---- storm -------------------------------------------------------------------------------

case_storm() {
    tree="$out/$name-tree"
    drive="$out/$name-drive.img"
    rates=${EXTFS_STORM_RATES:-0 1 10 100}
    rm -rf "$tree" "$drive"
    mkdir -p "$tree"
    seeded "$tree/src.bin" 64 13
    make_volume "$out/$name-data.img" 256 "$tree"
    make_drive "$drive" "$out/$name-data.img"
    rm -rf "$tree" "$out/$name-data.img"
    {
        echo "# generated by tools/extfs-test.sh: storm"
        echo "# storm copies /jam/src.bin (64 MiB of random bytes, put on the volume by the host's"
        echo "# mke2fs) to a new file on /jam while extfs-jam is killed $rates times a"
        echo "# second; each copy must MATCH (both files hashed again from the disk). A"
        echo "# marker built from \$T never appears in the typed line, only when the"
        echo "# command before it ran."
        echo "wait 120 Jam OS shell"
        echo "wait {prompt}"
        echo "seen 60 init: /data mounted"
        echo "send T=k"
        echo "wait {prompt}"
        echo "seen 60 init: /jam mounted"
        for k in $rates; do
            echo "send storm /jam/src.bin /jam/d$k.bin $k extfs-jam; echo s$k-\$T=\$?"
            echo "wait 900 s$k-k=0"
            echo "wait {prompt}"
            echo "send rm /jam/d$k.bin; echo r$k-\$T=\$?"
            echo "wait r$k-k=0"
            echo "wait {prompt}"
        done
        echo "send sync"
        echo "wait {prompt}"
        echo "send reboot -f"
        echo "wait reboot: resetting"
    } > "$out/$name.in"
    boot "$out/$name.in" "$drive"
    for k in $rates; do
        want 1 "\[shell\] storm: $k kills/s: .*; MATCH" "$run"
    done
    n=$(count "extfs /jam: restart \(killed" "$run")
    [ "$n" -ge 2 ] || { echo "$name: $n restarts of extfs /jam carried on, wanted 2 or more"; ok=0; }
    never "extfs /jam: restart .*starting fresh|giving up" "$run"
    never "DIFFERENT|MISMATCH" "$run"
    clean "$drive" $((256 << 20)) "after the run"
    rm -f "$drive"
}

ext_tools
case $c in
storm) case_storm ;;
*) echo "$name: no case called $c"; exit 2 ;;
esac
if [ $ok = 1 ]; then
    echo "$name: PASS"
    exit 0
fi
echo "$name: FAIL"
exit 1
