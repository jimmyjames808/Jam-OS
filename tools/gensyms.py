#!/usr/bin/env python3
"""Generate the kernel symbol table for backtraces.

  gensyms.py gen    <nm-output> <out.c>   write the table as C
  gensyms.py verify <nm-stage1> <nm-final> check no symbol moved

The table lives in the .ksyms section, which the linker script puts last,
so filling it in on the second link cannot shift any other address."""
import sys


def text_symbols(path):
    syms = []
    for line in open(path):
        parts = line.split()
        if len(parts) == 3 and parts[1] in "tT":
            syms.append((int(parts[0], 16), parts[2]))
    return sorted(set(syms))


def gen(nm_path, out_path):
    syms = text_symbols(nm_path)
    names = bytearray()
    entries = []
    for addr, name in syms:
        entries.append((addr, len(names)))
        names += name.encode() + b"\0"
    with open(out_path, "w") as f:
        f.write("/* Generated by tools/gensyms.py. Do not edit. */\n")
        f.write("#include <jam/ksyms.h>\n\n")
        f.write('#define KSYMS __attribute__((section(".ksyms")))\n\n')
        f.write("KSYMS const uint64_t ksyms_count = %d;\n" % len(entries))
        f.write("KSYMS const struct ksym ksyms_table[%d] = {\n" % max(len(entries), 1))
        for addr, off in entries:
            f.write("    { 0x%016xull, %d },\n" % (addr, off))
        f.write("};\n")
        f.write("KSYMS const char ksyms_names[%d] = {\n" % max(len(names), 1))
        for i in range(0, len(names), 16):
            f.write("    " + ", ".join(str(b) for b in names[i:i + 16]) + ",\n")
        f.write("};\n")


def verify(stage1, final):
    a = {n: addr for addr, n in text_symbols(stage1)}
    b = {n: addr for addr, n in text_symbols(final)}
    moved = [n for n in a if n in b and a[n] != b[n]]
    if moved:
        sys.exit("gensyms: symbols moved between links: " + ", ".join(moved[:10]))


if __name__ == "__main__":
    {"gen": gen, "verify": verify}[sys.argv[1]](*sys.argv[2:])
